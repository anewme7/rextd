package main

import "rex-td/rex"

type language string

const (
	chinese language = "zh"
	english language = "en"
)

func (l language) text(source string) string {
	if l == english {
		if translated, ok := englishUI[source]; ok {
			return translated
		}
	}
	return source
}

func (m *model) text(source string) string {
	return m.language.text(source)
}

func (m *model) sampleText(source string) string {
	if m.demo && m.language == english {
		if translated, ok := englishDemo[source]; ok {
			return translated
		}
	}
	return source
}

func (m *model) taskText(t *task, source string) string {
	if t.example {
		return m.sampleText(source)
	}
	return source
}

func (m *model) hostLabel(host rex.Host) string {
	if host.ID == "local" {
		return m.text("本机")
	}
	return host.Label
}

func (m *model) paneDisplayTitle(p rex.Pane) string {
	if title := reportedPaneTitle(p); title != "" {
		return m.sampleText(title)
	}
	return m.text("终端窗格")
}

